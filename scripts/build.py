#!/usr/bin/env python3
"""Build a self-contained JSTV entry; remote imports only fetch index/config files."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parent.parent
upstream=(root/'vendor/fangkuia-jstv.js').read_text()
patches=json.loads((root/'src/upstream-patches.json').read_text())
for patch in patches:
 before,after=patch['before'],patch['after']
 count=upstream.count(before)
 if count!=patch['count']:raise SystemExit(f"Patch {patch['id']} expected {patch['count']} matches, got {count}")
 upstream=upstream.replace(before,after)
def wrap(name,code):
 return 'const '+name+'=(()=>{const module={exports:{}};const exports=module.exports;\n'+code+'\nreturn module.exports;})();\n'
head='/* JSTV-myself 1.1.0. Generated by scripts/build.py. Embedded notices are retained. */\n'
head+='const __myselfHongguoSite={meta:{key:"hongguo_local",name:"红果短剧·独立版",type:3},api:async()=>{}};\n'
code=head+wrap('upstream',upstream)+wrap('hongguo',(root/'src/hongguo.js').read_text())+(root/'src/entry.js').read_text()
(root/'index.js').write_text(code)
for name in ['index.js','index.config.js']:
 (root/(name+'.md5')).write_text(hashlib.md5((root/name).read_bytes()).hexdigest())
print('Built index.js:',len(code.encode()),'bytes; checksums refreshed')
